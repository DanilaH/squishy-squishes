import { readdir, readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { spawnSync } from 'node:child_process';
import sharp from 'sharp';
const catalogIds = [...(await readFile('src/sandbox/roomCatalog.ts', 'utf8')).matchAll(/\{ id: '([^']+)'/g)].map(match => match[1]);
const selected = process.argv.slice(2);
if (selected.some(id => !catalogIds.includes(id))) throw new Error('Unknown selected room asset');
const ids = selected.length ? catalogIds.filter(id => selected.includes(id)) : catalogIds;
const present = new Set(await readdir('assets-src/room'));
const previous = selected.length ? JSON.parse(await readFile('assets-src/room/runtime-manifest.json', 'utf8')) : [];
const frames = Object.fromEntries(previous.filter(item => !ids.includes(item.id)).map(item => [item.id, item.frame]));
const manifest = previous.filter(item => !ids.includes(item.id));
for (const id of ids) {
  if (!present.has(`${id}.png`)) throw new Error(`Missing source ${id}`);
  const source = `assets-src/room/${id}.png`, output = `public/assets/room/${id}.webp`;
  const result = spawnSync(process.execPath, ['scripts/prepare-image.mjs', source, output, `--canvas=${(id === 'garland' || id === 'cobweb-garland') ? 480 : 300}`, '--padding=8', '--webp-quality=66', '--background=preserve', '--webp-only', '--force'], { encoding: 'utf8' });
  if (result.status !== 0) throw new Error(`${id}: ${result.stderr}\n${result.stdout}`);
  const { data, info } = await sharp(output).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  let left = info.width, top = info.height, right = -1, bottom = -1;
  for (let y = 0; y < info.height; y++) for (let x = 0; x < info.width; x++) if (data[(y * info.width + x) * 4 + 3] >= 16) { left = Math.min(left, x); top = Math.min(top, y); right = Math.max(right, x); bottom = Math.max(bottom, y); }
  if (right < left || bottom < top) throw new Error(`Empty asset ${id}`);
  frames[id] = { left, top, width: right - left + 1, height: bottom - top + 1, canvas: info.width };
  const sourceBytes = await readFile(source), runtimeBytes = await readFile(output);
  manifest.push({ id, source, output, sha256: createHash('sha256').update(sourceBytes).digest('hex'), runtimeSha256: createHash('sha256').update(runtimeBytes).digest('hex'), bytes: runtimeBytes.length, hasAvifCompanion: false, frame: frames[id] });
}
manifest.sort((a,b) => catalogIds.indexOf(a.id)-catalogIds.indexOf(b.id));
const orderedFrames = Object.fromEntries(catalogIds.map(id => [id, frames[id]]));
await writeFile('src/sandbox/roomAssetFrames.ts', '// Generated by scripts/prepare-room-assets.mjs; original square frames retained.\nexport const ROOM_ASSET_FRAMES: Readonly<Record<string, { left: number; top: number; width: number; height: number; canvas: number }>> = '+JSON.stringify(orderedFrames,null,2)+';\n');
await writeFile('assets-src/room/runtime-manifest.json', JSON.stringify(manifest,null,2)+'\n');
console.log(`Prepared ${manifest.length} room assets: ${manifest.reduce((sum,item)=>sum+item.bytes,0)} WebP bytes`);
